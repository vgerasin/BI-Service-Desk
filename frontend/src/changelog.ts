// История изменений системы, показывается всем пользователям на странице /changelog и коротко —
// версией в шапке. Каждый новый релиз добавляется первым элементом массива (самый свежий сверху).
// Даты — календарные дни, когда изменения были выпущены, а не отдельные правки внутри дня.
//
// У каждой строки изменения указаны роли, которых она касается — заявитель, исполнитель и
// администратор видят разный набор пунктов одного и того же релиза (ChangelogPage.tsx
// отфильтровывает по роли текущего пользователя, а релиз целиком скрывается, если после
// фильтрации для роли не осталось ни одного пункта).
export type ChangelogRole = 'customer' | 'executor' | 'admin';

export interface ChangelogChange {
  text: string;
  roles: ChangelogRole[];
}

export interface ChangelogEntry {
  version: string;
  date: string; // YYYY-MM-DD
  title: string;
  changes: ChangelogChange[];
}

